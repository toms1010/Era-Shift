for char, rows in FONT.items():
    assert len(rows) == 7, f"{char!r} has {len(rows)} rows"
    for row in rows:
        assert len(row) == 5, f"{char!r} row {row!r} is not 5 wide"

# Lowercase reuses the uppercase art.
for lower in "abcdefghijklmnopqrstuvwxyz":
    FONT[lower] = FONT[lower.upper()]

ordered = [chr(code) for code in range(32, 127)]
missing = [c for c in ordered if c not in FONT]
assert not missing, f"missing glyphs: {missing}"

lines = []
for char in ordered:
    flat = "".join(FONT[char]).replace("#", "#").replace(" ", ".")
    assert len(flat) == 35, f"{char!r} -> {len(flat)}"
    label = char if char not in ('\\',) else "\\\\"
    if char == ' ':
        label = "' '"
    lines.append(f'    /* {label:<4} */ "{flat}",')

import io
import re
import sys

target = sys.argv[1] if len(sys.argv) > 1 else "src/EraShift/Graphics/BitmapFont.cpp"
source = open(target, encoding="utf-8").read()
block = "\n".join(lines)
new_source, count = re.subn(
    r"(kGlyphArt = \{\n).*?(\n\};)",
    lambda m: m.group(1) + block + m.group(2),
    source,
    count=1,
    flags=re.S,
)
if count != 1:
    sys.exit("could not locate the kGlyphArt table")
open(target, "w", encoding="utf-8").write(new_source)
print(f"wrote {len(lines)} glyphs to {target}")
